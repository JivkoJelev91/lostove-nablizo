/**
 * Writes the scheme-aware colour variables into `global.css`.
 *
 * `tailwind.config.js` defines each scheme-aware token as a CSS custom property
 * (`--bg-main` and friends) rather than a fixed colour, so a component can style
 * `bg-bg-main` once and let the scheme decide the value. Those property values are derived
 * from `designSystem.json`, so they are generated here rather than hand-written: a copied
 * literal would drift from the design system with nothing to catch it.
 *
 * Run after changing any colour in `designSystem.json`:
 *   pnpm exec node scripts/write-theme-css.mjs
 */
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const { cssVariables } = require(join(root, 'tailwind.config.js'));

const banner = `/* Generated by scripts/write-theme-css.mjs from designSystem.json. Do not edit by hand. */`;

const contents = `${banner}
@tailwind base;
@tailwind components;
@tailwind utilities;

/*
 * Scheme-aware colour tokens. A component uses these through Tailwind classes
 * (bg-bg-main, text-text-primary, border-border) and never branches on the scheme.
 */
${cssVariables}
`;

await writeFile(join(root, 'global.css'), contents, 'utf8');
console.log('wrote global.css');
